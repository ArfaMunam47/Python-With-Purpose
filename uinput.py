#  type casting in python 1- int() 2- float() 3- eval()
# INT()
c=int(input('Enter ur lucky number:- '))
d=int(input('Enter ur worst number:- '))
print(c*d) # here we cant take float numbers

# FLOAT()
c=float(input('Enter ur lucky number:- '))
d=float(input('Enter ur worst number:- '))
print(c+d)

# EVAL() CAN TAKE ANY KIND OF NUMBERS HERE EVEN BINARY TOO
